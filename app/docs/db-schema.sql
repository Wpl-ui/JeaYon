-- 移除成员 = 软停用 + 遗留清理，四件事同一事务：
--   1) active=false（立即失去读写；旧会话下一个请求就被 RLS 拒）
--   2) 未完成且未归档的任务改为未分配（已完成 / 已归档保留历史负责人）
--   3) 重置邀请码（旧码立即失效）——接口层面「移除即换码」的保证来源
--   4) 返回被解绑的任务数，供界面提示
CREATE OR REPLACE FUNCTION public.app_remove_member(p_team_id bigint, p_user_id text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_uid TEXT := auth.uid();
  v_caller_role TEXT;
  v_target public.team_members%ROWTYPE;
  v_found BOOLEAN := false;
  v_new_code TEXT;
  v_tasks INT := 0;
BEGIN
  IF v_uid IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '未登录');
  END IF;
  v_caller_role := public.team_role(p_team_id);
  IF v_caller_role IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '你不是该团队的有效成员');
  END IF;
  IF v_caller_role NOT IN ('owner', 'admin') THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '仅群主或管理员可移除成员');
  END IF;
  IF p_user_id = v_uid THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '不能移除自己');
  END IF;

  SELECT * INTO v_target FROM public.team_members m
    WHERE m.team_id = p_team_id AND m.user_id = p_user_id FOR UPDATE;
  v_found := FOUND;
  IF NOT v_found OR NOT v_target.active THEN
    RETURN jsonb_build_object('ok', false, 'code', 'not_found', 'message', '成员不存在或已停用');
  END IF;
  IF v_target.role = 'owner' THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '不能移除群主');
  END IF;
  IF v_caller_role = 'admin' AND v_target.role <> 'member' THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '管理员只能移除普通成员');
  END IF;

  UPDATE public.team_members
    SET active = false, deactivated_at = now()
    WHERE id = v_target.id;

  UPDATE public.tasks t
    SET assignee_id = NULL, version = t.version + 1, updated_at = now()
    WHERE t.team_id = p_team_id AND t.assignee_id = p_user_id
      AND t.status <> 'done' AND t.archived_at IS NULL;
  GET DIAGNOSTICS v_tasks = ROW_COUNT;

  v_new_code := public.app_new_invite_code();
  UPDATE public.team_invites SET code = v_new_code, updated_at = now(), updated_by = v_uid
    WHERE team_id = p_team_id;

  RETURN jsonb_build_object('ok', true, 'code', 'ok', 'message', '成员已移除，邀请码已重置',
    'data', jsonb_build_object('user_id', p_user_id, 'unassigned_tasks', v_tasks, 'invite_code', v_new_code));
END;
$function$;


