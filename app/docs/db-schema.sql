-- 10. 成员管理与邀请码 RPC
-- -----------------------------------------------------------------------------
-- 角色变更只有 owner 能做，且只能改成 admin / member（owner 不可授、不可转）。
CREATE OR REPLACE FUNCTION public.app_set_member_role(p_team_id bigint, p_user_id text, p_role text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_uid TEXT := auth.uid();
  v_caller_role TEXT;
  v_target public.team_members%ROWTYPE;
  v_found BOOLEAN := false;
BEGIN
  IF v_uid IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '未登录');
  END IF;
  IF p_role IS NULL OR p_role NOT IN ('admin', 'member') THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '角色只能是 admin 或 member');
  END IF;
  v_caller_role := public.team_role(p_team_id);
  IF v_caller_role IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '你不是该团队的有效成员');
  END IF;
  IF v_caller_role <> 'owner' THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '仅群主可变更成员角色');
  END IF;
  IF p_user_id = v_uid THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '不能修改自己的角色（首版不支持群主转让）');
