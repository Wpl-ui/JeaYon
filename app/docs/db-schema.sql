-- 13. 行级安全策略（第二道门：行）
-- -----------------------------------------------------------------------------
-- 全部 5 张表已 ENABLE ROW LEVEL SECURITY。判定统一走 team_role(team_id)：
-- 返回非 NULL = 我是该队的有效成员。被停用后 team_role 变 NULL，策略立刻失效，
-- 不需要等会话过期。
ALTER TABLE public.teams        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.team_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.team_invites ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tasks        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.work_logs    ENABLE ROW LEVEL SECURITY;

-- teams：只能读自己所属的团队
CREATE POLICY teams_select_member ON public.teams
  FOR SELECT TO authenticated
  USING (public.team_role(id) IS NOT NULL);

-- team_members：能读本团队成员（含已停用的行，用于展示历史姓名）
CREATE POLICY team_members_select_member ON public.team_members
  FOR SELECT TO authenticated
  USING (public.team_role(team_id) IS NOT NULL);

-- tasks：能读本团队任务（归档任务也在内，由前端筛选）
CREATE POLICY tasks_select_member ON public.tasks
  FOR SELECT TO authenticated
  USING (public.team_role(team_id) IS NOT NULL);

-- tasks INSERT：必须是我所在团队 + 创建者必须是我本人 + 负责人（若填）必须是
-- 本团队的有效成员。客户端无法伪造 created_by 或把任务塞进别人的团队。
CREATE POLICY tasks_insert_member ON public.tasks
  FOR INSERT TO authenticated
  WITH CHECK (
    public.team_role(team_id) IS NOT NULL
    AND created_by = auth.uid()
    AND (
      assignee_id IS NULL
      OR EXISTS (
        SELECT 1 FROM public.team_members m
        WHERE m.team_id = tasks.team_id AND m.user_id = tasks.assignee_id AND m.active
      )
    )
  );

-- work_logs：能读本团队日报
CREATE POLICY work_logs_select_member ON public.work_logs
  FOR SELECT TO authenticated
  USING (public.team_role(team_id) IS NOT NULL);

-- work_logs INSERT：作者必须是我本人 + 关联任务（若填）必须是本团队未归档任务
CREATE POLICY work_logs_insert_member ON public.work_logs
  FOR INSERT TO authenticated
  WITH CHECK (
    public.team_role(team_id) IS NOT NULL
    AND owner_id = auth.uid()
    AND (
      related_task_id IS NULL
      OR EXISTS (
        SELECT 1 FROM public.tasks t
        WHERE t.id = work_logs.related_task_id
          AND t.team_id = work_logs.team_id
          AND t.archived_at IS NULL
      )
    )
  );

