-- -----------------------------------------------------------------------------
-- 1. teams 团队
-- -----------------------------------------------------------------------------
CREATE TABLE public.teams (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text        NOT NULL,
  timezone    text        NOT NULL DEFAULT 'Asia/Shanghai',
  created_by  text        NOT NULL DEFAULT auth.uid(),
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT teams_name_check
    CHECK (char_length(btrim(name)) >= 1 AND char_length(btrim(name)) <= 40),
  -- 首版只支持单一团队时区，写死在约束里，避免"看起来可配、实际不支持"
  CONSTRAINT teams_timezone_check
    CHECK (timezone = 'Asia/Shanghai')
);

COMMENT ON TABLE public.teams IS '团队（首版时区固定 Asia/Shanghai）';


-- -----------------------------------------------------------------------------
-- 2. team_members 成员与角色
-- -----------------------------------------------------------------------------
-- 移除成员为 active = false 的软停用：保留行 → 历史日报的作者姓名、任务的历史负责人
-- 都还能解析到人；重新加入时走 app_join_team 把同一行激活并降级为 member。
CREATE TABLE public.team_members (
  id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id         bigint      NOT NULL REFERENCES public.teams(id),
  user_id         text        NOT NULL,
  role            text        NOT NULL DEFAULT 'member',
  active          boolean     NOT NULL DEFAULT true,
  display_name    text        NOT NULL,
  joined_at       timestamptz NOT NULL DEFAULT now(),
  deactivated_at  timestamptz,
  CONSTRAINT team_members_team_user_key UNIQUE (team_id, user_id),
  CONSTRAINT team_members_role_check
    CHECK (role IN ('owner', 'admin', 'member')),
  CONSTRAINT team_members_display_name_check
    CHECK (char_length(btrim(display_name)) >= 1 AND char_length(btrim(display_name)) <= 40)
);

COMMENT ON TABLE public.team_members IS '团队成员与角色；移除为 active=false 停用，保留历史姓名';

CREATE INDEX team_members_user_idx ON public.team_members (user_id);


-- -----------------------------------------------------------------------------
-- 3. team_invites 邀请码（受限记录）
-- -----------------------------------------------------------------------------
-- 一团队一码，重置即覆盖。该表对 anon / authenticated **零授权**，
-- 只有 SECURITY DEFINER RPC 能读写，因此普通成员即使直接查 API 也拿不到别队邀请码。
CREATE TABLE public.team_invites (
  team_id     bigint      PRIMARY KEY REFERENCES public.teams(id) ON DELETE CASCADE,
  code        text        NOT NULL,
  updated_at  timestamptz NOT NULL DEFAULT now(),
  updated_by  text,
  CONSTRAINT team_invites_code_key UNIQUE (code),
  -- 10 位大写字母/数字，由 gen_random_uuid() 派生（PG 内置 CSPRNG），非 Math.random
  CONSTRAINT team_invites_code_check CHECK (code ~ '^[A-Z0-9]{10}$')
);

COMMENT ON TABLE public.team_invites IS '团队邀请码（受限：不授予任何表权限，仅经受控 RPC 访问）';


-- -----------------------------------------------------------------------------
-- 4. tasks 任务
-- -----------------------------------------------------------------------------
-- 状态与进度的一致性下沉到 CHECK：todo=0、in_progress=1..99、done=100。
-- 前端 src/lib/progress.ts 是同一套规则的镜像，用于即时反馈，不作为最终依据。
CREATE TABLE public.tasks (
  id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id      bigint      NOT NULL REFERENCES public.teams(id),
  created_by   text        NOT NULL DEFAULT auth.uid(),
  assignee_id  text,
  title        text        NOT NULL,
  description  text,
  status       text        NOT NULL DEFAULT 'todo',
  progress     smallint    NOT NULL DEFAULT 0,
  start_date   date        NOT NULL,
  due_date     date        NOT NULL,
  archived_at  timestamptz,
  version      integer     NOT NULL DEFAULT 1,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),

  -- 供 work_logs 的复合外键引用，使"关联任务必须同团队"由数据库保证
  CONSTRAINT tasks_team_id_key UNIQUE (team_id, id),

  -- MATCH SIMPLE（默认）：assignee_id 为 NULL 时整条外键跳过校验，
  -- 因此"未分配"天然合法；一旦填人，就必须是该团队的有效成员行。
  CONSTRAINT tasks_team_assignee_fk
    FOREIGN KEY (team_id, assignee_id)
    REFERENCES public.team_members (team_id, user_id),

  CONSTRAINT tasks_title_check
    CHECK (char_length(btrim(title)) >= 1 AND char_length(btrim(title)) <= 120),
  CONSTRAINT tasks_status_check
    CHECK (status IN ('todo', 'in_progress', 'done')),
  CONSTRAINT tasks_progress_check
    CHECK (progress >= 0 AND progress <= 100),
  CONSTRAINT tasks_status_progress_ok
    CHECK (
      (status = 'todo'        AND progress = 0)  OR
      (status = 'in_progress' AND progress BETWEEN 1 AND 99) OR
      (status = 'done'        AND progress = 100)
    ),
  -- 截止不早于开始；起止同日合法（甘特图上显示为 1 天宽）
  CONSTRAINT tasks_dates_ok CHECK (due_date >= start_date)
);

COMMENT ON TABLE public.tasks IS
  '团队任务；归档为 archived_at 非空，不物理删除；更新必须经营主 RPC 并携带 expected_version';

CREATE INDEX tasks_team_archived_idx ON public.tasks (team_id, archived_at);
CREATE INDEX tasks_team_assignee_idx ON public.tasks (team_id, assignee_id);
CREATE INDEX tasks_team_due_idx      ON public.tasks (team_id, due_date);
CREATE INDEX tasks_team_status_idx   ON public.tasks (team_id, status);


-- -----------------------------------------------------------------------------
-- 5. work_logs 标准日报
-- -----------------------------------------------------------------------------
-- (team_id, owner_id, work_date) 唯一 —— "每人每团队每天最多一篇"由数据库兜底，
-- 前端重复提交只会拿到 23505，不会被静默覆盖成两篇。
-- owner_name 是写入时的姓名快照：成员被停用后，历史日报仍显示当时的署名。
CREATE TABLE public.work_logs (
  id               bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id          bigint      NOT NULL REFERENCES public.teams(id),
  owner_id         text        NOT NULL DEFAULT auth.uid(),
  owner_name       text        NOT NULL,
  work_date        date        NOT NULL,
  done_today       text        NOT NULL,
  problems         text,
  plan_tomorrow    text        NOT NULL,
  hours            numeric,
  related_task_id  bigint,
  version          integer     NOT NULL DEFAULT 1,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT work_logs_team_owner_date_key UNIQUE (team_id, owner_id, work_date),

  CONSTRAINT work_logs_team_task_fk
    FOREIGN KEY (team_id, related_task_id)
    REFERENCES public.tasks (team_id, id),

  CONSTRAINT work_logs_owner_name_check
    CHECK (char_length(btrim(owner_name)) >= 1 AND char_length(btrim(owner_name)) <= 40),
  CONSTRAINT work_logs_done_today_check    CHECK (char_length(btrim(done_today)) > 0),
  CONSTRAINT work_logs_plan_tomorrow_check CHECK (char_length(btrim(plan_tomorrow)) > 0),
  -- 工时可空（= 未填）；填了就必须 0–24，两位小数由前端 normalizeHours 收敛
  CONSTRAINT work_logs_hours_check
    CHECK (hours IS NULL OR (hours >= 0 AND hours <= 24))
);

COMMENT ON TABLE public.work_logs IS
  '标准日报；每人每团队每天最多一篇（team_id,owner_id,work_date 唯一）';

CREATE INDEX work_logs_team_date_idx ON public.work_logs (team_id, work_date DESC);


-- -----------------------------------------------------------------------------
-- 6. 内部函数
-- -----------------------------------------------------------------------------
-- team_role 存在的唯一目的是绕开 RLS 策略递归：team_members 的 SELECT 策略需要
-- 判断"我是不是这队成员"，直接查自己会再次触发策略。SECURITY DEFINER 让它以表主
-- 身份读取，只回一个 role 字符串（未激活/不存在返回 NULL），不泄露其它字段。
CREATE OR REPLACE FUNCTION public.team_role(p_team_id bigint)
RETURNS text
LANGUAGE sql
STABLE SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
  SELECT m.role FROM public.team_members m
  WHERE m.team_id = p_team_id AND m.user_id = auth.uid() AND m.active
  LIMIT 1
$function$;


-- 邀请码生成：从 gen_random_uuid()（PG 内置 CSPRNG）取前 10 位大写十六进制字符，
-- 碰撞则重试，最多 20 次。只授权给 service_role，业务侧经 app_create_team /
-- app_reset_invite_code 间接触发，用户无法直接调用无限刷码。
CREATE OR REPLACE FUNCTION public.app_new_invite_code()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_code TEXT;
  v_try INT := 0;
BEGIN
  LOOP
    v_code := upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10));
    EXIT WHEN NOT EXISTS (SELECT 1 FROM public.team_invites i WHERE i.code = v_code);
    v_try := v_try + 1;
    IF v_try > 20 THEN
      RAISE EXCEPTION 'invite_code_generation_failed';
    END IF;
  END LOOP;
  RETURN v_code;
END;
$function$;


-- -----------------------------------------------------------------------------
-- 7. 团队 RPC
-- -----------------------------------------------------------------------------
-- 约定：全部返回 jsonb 信封 { ok, code, message, data? }，不抛异常给客户端，
-- 让前端能区分 conflict / forbidden / invalid 并给出不同 UI，而不是一律"操作失败"。

-- 创建团队：建团队 + 把自己写为 owner + 生成首个邀请码，三步同一事务。
CREATE OR REPLACE FUNCTION public.app_create_team(p_name text, p_display_name text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_uid TEXT := auth.uid();
  v_name TEXT := btrim(coalesce(p_name, ''));
  v_display TEXT := btrim(coalesce(p_display_name, ''));
  v_team_id BIGINT;
  v_code TEXT;
BEGIN
  IF v_uid IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '未登录');
  END IF;
  IF char_length(v_name) < 1 OR char_length(v_name) > 40 THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '团队名称需为 1-40 个字符');
  END IF;
  IF char_length(v_display) < 1 OR char_length(v_display) > 40 THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '姓名需为 1-40 个字符');
  END IF;

  INSERT INTO public.teams (name, created_by) VALUES (v_name, v_uid) RETURNING id INTO v_team_id;
  INSERT INTO public.team_members (team_id, user_id, role, display_name)
    VALUES (v_team_id, v_uid, 'owner', v_display);
  v_code := public.app_new_invite_code();
  INSERT INTO public.team_invites (team_id, code, updated_by) VALUES (v_team_id, v_code, v_uid);

  RETURN jsonb_build_object('ok', true, 'code', 'ok', 'message', '团队已创建',
    'data', jsonb_build_object('team_id', v_team_id, 'name', v_name, 'role', 'owner', 'invite_code', v_code));
END;
$function$;


-- 用邀请码加入 / 重新加入。
-- 重新加入的语义：同一 (team_id, user_id) 行被激活，role 强制回落为 member，
-- 不恢复被移除前的 admin —— 旧管理权限不会随邀请码一起回来。
CREATE OR REPLACE FUNCTION public.app_join_team(p_code text, p_display_name text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_uid TEXT := auth.uid();
  v_code TEXT := upper(btrim(coalesce(p_code, '')));
  v_display TEXT := btrim(coalesce(p_display_name, ''));
  v_team_id BIGINT;
  v_team_name TEXT;
  v_member public.team_members%ROWTYPE;
  v_found BOOLEAN := false;
BEGIN
  IF v_uid IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '未登录');
  END IF;
  IF char_length(v_code) = 0 THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '请输入邀请码');
  END IF;

  SELECT i.team_id INTO v_team_id FROM public.team_invites i WHERE i.code = v_code;
  IF v_team_id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid_code', 'message', '邀请码无效或已重置');
  END IF;

  SELECT t.name INTO v_team_name FROM public.teams t WHERE t.id = v_team_id;

  SELECT * INTO v_member FROM public.team_members m
    WHERE m.team_id = v_team_id AND m.user_id = v_uid FOR UPDATE;
  v_found := FOUND;

  IF v_found AND v_member.active THEN
    RETURN jsonb_build_object('ok', false, 'code', 'already_member', 'message', '你已在该团队中',
      'data', jsonb_build_object('team_id', v_team_id, 'role', v_member.role));
  END IF;

  IF v_found THEN
    UPDATE public.team_members m
      SET active = true, role = 'member', deactivated_at = NULL, joined_at = now(),
          display_name = coalesce(nullif(v_display, ''), m.display_name)
      WHERE m.id = v_member.id;
    RETURN jsonb_build_object('ok', true, 'code', 'ok', 'message', '已重新加入团队',
      'data', jsonb_build_object('team_id', v_team_id, 'name', v_team_name, 'role', 'member'));
  END IF;

  IF char_length(v_display) < 1 OR char_length(v_display) > 40 THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '请填写 1-40 个字符的姓名');
  END IF;

  INSERT INTO public.team_members (team_id, user_id, role, display_name)
    VALUES (v_team_id, v_uid, 'member', v_display);

  RETURN jsonb_build_object('ok', true, 'code', 'ok', 'message', '已加入团队',
    'data', jsonb_build_object('team_id', v_team_id, 'name', v_team_name, 'role', 'member'));
END;
$function$;


-- 读取邀请码：仅 owner / admin。普通成员走这条路会被明确拒绝，
-- 而不是"查不到所以返回空"。
CREATE OR REPLACE FUNCTION public.app_get_invite_code(p_team_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_uid TEXT := auth.uid();
  v_role TEXT;
  v_code TEXT;
BEGIN
  IF v_uid IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '未登录');
  END IF;
  v_role := public.team_role(p_team_id);
  IF v_role IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '你不是该团队的有效成员');
  END IF;
  IF v_role NOT IN ('owner', 'admin') THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '仅群主或管理员可查看邀请码');
  END IF;
  SELECT i.code INTO v_code FROM public.team_invites i WHERE i.team_id = p_team_id;
  IF v_code IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'not_found', 'message', '邀请码不存在');
  END IF;
  RETURN jsonb_build_object('ok', true, 'code', 'ok', 'message', 'ok',
    'data', jsonb_build_object('team_id', p_team_id, 'invite_code', v_code));
END;
$function$;


-- -----------------------------------------------------------------------------
-- 8. 任务 RPC（写操作唯一入口）
-- -----------------------------------------------------------------------------
-- 并发控制：SELECT ... FOR UPDATE 锁行 → 比对 version → 不符直接 conflict 返回，
-- 不覆盖、不推进版本。符合才 UPDATE ... version + 1。整段在单事务内，天然原子。
CREATE OR REPLACE FUNCTION public.app_task_update(p_payload jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_uid TEXT := auth.uid();
  v_task_id BIGINT := nullif(p_payload->>'task_id', '')::BIGINT;
  v_expected INT := coalesce(nullif(p_payload->>'expected_version', '')::INT, -1);
  v_title TEXT := btrim(coalesce(p_payload->>'title', ''));
  v_desc TEXT := nullif(btrim(coalesce(p_payload->>'description', '')), '');
  v_assignee TEXT := nullif(btrim(coalesce(p_payload->>'assignee_id', '')), '');
  v_status TEXT := coalesce(nullif(p_payload->>'status', ''), 'todo');
  v_progress INT := coalesce(nullif(p_payload->>'progress', '')::INT, 0);
  v_start_txt TEXT := nullif(p_payload->>'start_date', '');
  v_due_txt TEXT := nullif(p_payload->>'due_date', '');
  v_start DATE;
  v_due DATE;
  v_role TEXT;
  v_task public.tasks%ROWTYPE;
  v_found BOOLEAN := false;
BEGIN
  IF v_uid IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '未登录');
  END IF;
  IF v_task_id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '缺少任务 ID');
  END IF;

  SELECT * INTO v_task FROM public.tasks t WHERE t.id = v_task_id FOR UPDATE;
  v_found := FOUND;
  IF NOT v_found THEN
    RETURN jsonb_build_object('ok', false, 'code', 'not_found', 'message', '任务不存在');
  END IF;
  v_role := public.team_role(v_task.team_id);
  IF v_role IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '你不是该团队的有效成员');
  END IF;
  IF v_task.archived_at IS NOT NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '任务已归档，不能编辑');
  END IF;
  IF v_task.version <> v_expected THEN
    RETURN jsonb_build_object('ok', false, 'code', 'conflict', 'message', '数据已被其他人修改，请重新加载',
      'data', jsonb_build_object('current_version', v_task.version));
  END IF;

  IF char_length(v_title) < 1 OR char_length(v_title) > 120 THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '任务标题需为 1-120 个字符');
  END IF;
  IF v_desc IS NOT NULL AND char_length(v_desc) > 2000 THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '描述不能超过 2000 个字符');
  END IF;
  IF v_status NOT IN ('todo', 'in_progress', 'done') THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '任务状态无效');
  END IF;
  IF v_start_txt IS NULL OR v_due_txt IS NULL
     OR v_start_txt !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' OR v_due_txt !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '请填写开始日期和截止日期');
  END IF;
  BEGIN
    v_start := v_start_txt::date;
    v_due := v_due_txt::date;
  EXCEPTION WHEN others THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '日期格式无效');
  END;
  IF v_due < v_start THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '截止日期不能早于开始日期');
  END IF;
  IF v_assignee IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.team_members m
      WHERE m.team_id = v_task.team_id AND m.user_id = v_assignee AND m.active) THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '负责人必须是本团队的有效成员');
  END IF;

  -- 状态是权威，进度跟着状态收敛；in_progress 的 0/100 会被夹到 1/99，
  -- 保证不会写出违反 tasks_status_progress_ok 的行。
  IF v_status = 'todo' THEN
    v_progress := 0;
  ELSIF v_status = 'done' THEN
    v_progress := 100;
  ELSE
    IF v_progress < 1 THEN v_progress := 1; END IF;
    IF v_progress > 99 THEN v_progress := 99; END IF;
  END IF;

  UPDATE public.tasks SET
      title = v_title,
      description = v_desc,
      assignee_id = v_assignee,
      status = v_status,
      progress = v_progress,
      start_date = v_start,
      due_date = v_due,
      version = v_task.version + 1,
      updated_at = now()
    WHERE id = v_task_id
    RETURNING * INTO v_task;

  RETURN jsonb_build_object('ok', true, 'code', 'ok', 'message', '已保存',
    'data', jsonb_build_object(
      'id', v_task.id, 'team_id', v_task.team_id, 'title', v_task.title,
      'description', v_task.description, 'assignee_id', v_task.assignee_id,
      'status', v_task.status, 'progress', v_task.progress,
      'start_date', v_task.start_date::text, 'due_date', v_task.due_date::text,
      'archived_at', v_task.archived_at::text, 'version', v_task.version,
      'created_by', v_task.created_by, 'updated_at', v_task.updated_at::text));
END;
$function$;


-- 归档 / 取消归档。不物理删除：archived_at 非空即退出列表与甘特图，
-- 但 work_logs.related_task_id 仍能解析到它，历史日报的关联不会断。
CREATE OR REPLACE FUNCTION public.app_task_archive(p_task_id bigint, p_expected_version integer, p_archived boolean)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_uid TEXT := auth.uid();
  v_role TEXT;
  v_task public.tasks%ROWTYPE;
  v_found BOOLEAN := false;
  v_assignee TEXT;
BEGIN
  IF v_uid IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '未登录');
  END IF;
  SELECT * INTO v_task FROM public.tasks t WHERE t.id = p_task_id FOR UPDATE;
  v_found := FOUND;
  IF NOT v_found THEN
    RETURN jsonb_build_object('ok', false, 'code', 'not_found', 'message', '任务不存在');
  END IF;
  v_role := public.team_role(v_task.team_id);
  IF v_role IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '你不是该团队的有效成员');
  END IF;
  IF v_task.version <> p_expected_version THEN
    RETURN jsonb_build_object('ok', false, 'code', 'conflict', 'message', '数据已被其他人修改，请重新加载',
      'data', jsonb_build_object('current_version', v_task.version));
  END IF;

  -- 取消归档时若原负责人已离队，则落回未分配，避免恢复出一个无效负责人
  v_assignee := v_task.assignee_id;
  IF coalesce(p_archived, true) = false AND v_assignee IS NOT NULL THEN
    IF NOT EXISTS (SELECT 1 FROM public.team_members m
        WHERE m.team_id = v_task.team_id AND m.user_id = v_assignee AND m.active) THEN
      v_assignee := NULL;
    END IF;
  END IF;

  UPDATE public.tasks SET
      archived_at = CASE WHEN coalesce(p_archived, true) THEN now() ELSE NULL END,
      assignee_id = v_assignee,
      version = v_task.version + 1,
      updated_at = now()
    WHERE id = p_task_id
    RETURNING * INTO v_task;

  RETURN jsonb_build_object('ok', true, 'code', 'ok',
    'message', CASE WHEN p_archived THEN '任务已归档' ELSE '任务已恢复' END,
    'data', jsonb_build_object(
      'id', v_task.id, 'team_id', v_task.team_id, 'archived_at', v_task.archived_at::text,
      'assignee_id', v_task.assignee_id, 'version', v_task.version, 'updated_at', v_task.updated_at::text));
END;
$function$;


-- -----------------------------------------------------------------------------
-- 9. 日报 RPC（写操作唯一入口）
-- -----------------------------------------------------------------------------
-- 只能改自己的：owner_id = auth.uid() 与 team_role 非空两道校验，
-- 所以被移出团队的作者即使还留着旧会话，也改不动自己从前的日报。
CREATE OR REPLACE FUNCTION public.app_worklog_update(p_payload jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_uid TEXT := auth.uid();
  v_log_id BIGINT := nullif(p_payload->>'log_id', '')::BIGINT;
  v_expected INT := coalesce(nullif(p_payload->>'expected_version', '')::INT, -1);
  v_date_txt TEXT := nullif(p_payload->>'work_date', '');
  v_done TEXT := btrim(coalesce(p_payload->>'done_today', ''));
  v_problems TEXT := nullif(btrim(coalesce(p_payload->>'problems', '')), '');
  v_plan TEXT := btrim(coalesce(p_payload->>'plan_tomorrow', ''));
  v_hours_txt TEXT := nullif(p_payload->>'hours', '');
  v_hours NUMERIC(5,2);
  v_related BIGINT := nullif(p_payload->>'related_task_id', '')::BIGINT;
  v_date DATE;
  v_log public.work_logs%ROWTYPE;
  v_found BOOLEAN := false;
BEGIN
  IF v_uid IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '未登录');
  END IF;
  IF v_log_id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '缺少日报 ID');
  END IF;

  SELECT * INTO v_log FROM public.work_logs w WHERE w.id = v_log_id FOR UPDATE;
  v_found := FOUND;
  IF NOT v_found THEN
    RETURN jsonb_build_object('ok', false, 'code', 'not_found', 'message', '日报不存在');
  END IF;
  IF public.team_role(v_log.team_id) IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '你不是该团队的有效成员');
  END IF;
  IF v_log.owner_id <> v_uid THEN
    RETURN jsonb_build_object('ok', false, 'code', 'forbidden', 'message', '只能修改自己的日报');
  END IF;
  IF v_log.version <> v_expected THEN
    RETURN jsonb_build_object('ok', false, 'code', 'conflict', 'message', '数据已被修改，请重新加载',
      'data', jsonb_build_object('current_version', v_log.version));
  END IF;

  IF v_date_txt IS NULL OR v_date_txt !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '工作日期格式无效');
  END IF;
  BEGIN
    v_date := v_date_txt::date;
  EXCEPTION WHEN others THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '工作日期无效');
  END;
  IF char_length(v_done) < 1 OR char_length(v_done) > 2000 THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '今日完成需为 1-2000 个字符');
  END IF;
  IF char_length(v_plan) < 1 OR char_length(v_plan) > 2000 THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '明日计划需为 1-2000 个字符');
  END IF;
  IF v_problems IS NOT NULL AND char_length(v_problems) > 2000 THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '遇到问题不能超过 2000 个字符');
  END IF;
  IF v_hours_txt IS NOT NULL THEN
    IF v_hours_txt !~ '^[0-9]{1,2}(\.[0-9]{1,2})?$' THEN
      RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '工时需为 0-24 的数字，最多两位小数');
    END IF;
    v_hours := v_hours_txt::numeric(5,2);
    IF v_hours < 0 OR v_hours > 24 THEN
      RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '工时需在 0-24 之间');
    END IF;
  END IF;
  -- 只有"换了关联任务"才校验归档状态：原任务事后被归档时，历史关联仍然保留
  IF v_related IS NOT NULL AND v_related <> coalesce(v_log.related_task_id, -1) THEN
    IF NOT EXISTS (SELECT 1 FROM public.tasks t
        WHERE t.id = v_related AND t.team_id = v_log.team_id AND t.archived_at IS NULL) THEN
      RETURN jsonb_build_object('ok', false, 'code', 'invalid', 'message', '关联任务必须是本团队未归档的任务');
    END IF;
  END IF;

  BEGIN
    UPDATE public.work_logs SET
        work_date = v_date,
        done_today = v_done,
        problems = v_problems,
        plan_tomorrow = v_plan,
        hours = v_hours,
        related_task_id = v_related,
        version = v_log.version + 1,
        updated_at = now()
      WHERE id = v_log_id
      RETURNING * INTO v_log;
  EXCEPTION WHEN unique_violation THEN
    -- 改日期时撞上自己另一篇日报，明确告知而不是静默吞掉
    RETURN jsonb_build_object('ok', false, 'code', 'already_exists', 'message', '该日期已有日报，请直接编辑那一篇');
  END;

  RETURN jsonb_build_object('ok', true, 'code', 'ok', 'message', '已保存',
    'data', jsonb_build_object(
      'id', v_log.id, 'team_id', v_log.team_id, 'owner_id', v_log.owner_id,
      'owner_name', v_log.owner_name, 'work_date', v_log.work_date::text,
      'done_today', v_log.done_today, 'problems', v_log.problems,
      'plan_tomorrow', v_log.plan_tomorrow, 'hours', v_log.hours,
      'related_task_id', v_log.related_task_id, 'version', v_log.version,
      'updated_at', v_log.updated_at::text));
END;
$function$;


