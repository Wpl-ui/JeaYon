  END IF;

  UPDATE public.team_members SET role = p_role WHERE id = v_target.id;

  RETURN jsonb_build_object('ok', true, 'code', 'ok', 'message',
      CASE WHEN p_role = 'admin' THEN '已设为管理员' ELSE '已取消管理员' END,
    'data', jsonb_build_object('user_id', p_user_id, 'role', p_role));
END;
